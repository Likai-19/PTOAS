// This test verifies that pto.print (routed through the bridge-generated
// cce::printf wrapper) coexists with data-transfer ops in one kernel. The
// kernel loads 64 f32 values from GM to UB, prints two diagnostic scalars
// via DebugTunnel, then stores the UB buffer to the output GM pointer. The
// host compares the output buffer against the input — a correct passthrough
// proves the print pipeline (DTData ABI wiring, wrapper compilation and the
// host-side DebugTunnel close override) did not disturb the kernel.

#include "test_common.h"
#include "acl/acl.h"
#include <cstdint>
#include <cstdio>
#include <cstdlib>

using namespace PtoTestCommon;

#define ACL_CHECK(expr)                                                          \
  do {                                                                           \
    const aclError _ret = (expr);                                                \
    if (_ret != ACL_SUCCESS) {                                                   \
      std::fprintf(stderr, "[ERROR] %s failed: %d (%s:%d)\n", #expr,             \
                   (int)_ret, __FILE__, __LINE__);                               \
      const char *_recent = aclGetRecentErrMsg();                                \
      const bool hasRecent = _recent != nullptr && _recent[0] != '\0';          \
      if (hasRecent) {                                                           \
        std::fprintf(stderr, "[ERROR] RecentErrMsg: %s\n", _recent);             \
      }                                                                          \
      rc = 1;                                                                    \
      goto cleanup;                                                              \
    }                                                                            \
  } while (0)

void LaunchPrint_bridge_kernel_mix_aiv(void *dtData, float *v1, float *v2,
                                       float v3, int32_t v4,
                                       void *stream);

// Exported by the ptoas-generated fatobj (DebugTunnel host machinery).
extern "C" void *__DebugTunnel_Open(unsigned blockNum);
extern "C" void __DebugTunnel_Close(void *data, void *stream);

int main() {
  constexpr size_t kElemCount = 64;
  constexpr size_t kFileSize = kElemCount * sizeof(float);
  const float offsetHost = 1.5f;
  const int32_t nHost = static_cast<int32_t>(kElemCount);

  float *v1Host = nullptr, *v2Host = nullptr;
  float *v1Device = nullptr, *v2Device = nullptr;

  int rc = 0;
  bool aclInited = false;
  bool deviceSet = false;
  int deviceId = 0;
  aclrtStream stream = nullptr;
  size_t fileSize = 0;
  void *dtData = nullptr;

  ACL_CHECK(aclInit(nullptr));
  aclInited = true;
  {
    const char *envDevice = std::getenv("ACL_DEVICE_ID");
    if (envDevice != nullptr) {
      char *envEnd = nullptr;
      const long parsed = std::strtol(envDevice, &envEnd, 10);
      const bool usable = envEnd != envDevice && *envEnd == '\0' &&
                          parsed >= 0 && parsed <= INT32_MAX;
      if (!usable) {
        std::fprintf(stderr, "[ERROR] Invalid ACL_DEVICE_ID: %s\n", envDevice);
        return 1;
      }
      deviceId = (int32_t)parsed;
    }
  }
  ACL_CHECK(aclrtSetDevice(deviceId));
  deviceSet = true;
  ACL_CHECK(aclrtCreateStream(&stream));

  ACL_CHECK(aclrtMallocHost((void **)(&v1Host), kFileSize));
  ACL_CHECK(aclrtMallocHost((void **)(&v2Host), kFileSize));
  ACL_CHECK(aclrtMalloc((void **)&v1Device, kFileSize, ACL_MEM_MALLOC_HUGE_FIRST));
  ACL_CHECK(aclrtMalloc((void **)&v2Device, kFileSize, ACL_MEM_MALLOC_HUGE_FIRST));

  // Read input data generated by golden.py.
  {
    const bool inputRead =
        ReadFile("./v1.bin", fileSize, v1Host, kFileSize) &&
        fileSize == kFileSize;
    if (!inputRead) {
      std::fprintf(stderr,
                   "[ERROR] Failed to read ./v1.bin (expected %zu bytes, got %zu)\n",
                   kFileSize, fileSize);
      rc = 1;
      goto cleanup;
    }
  }

  ACL_CHECK(aclrtMemcpy(v1Device, kFileSize, v1Host, kFileSize,
                        ACL_MEMCPY_HOST_TO_DEVICE));

  // Open the DebugTunnel explicitly and hand the DTData to the kernel as a
  // regular user argument (the kernel's first parameter).
  dtData = __DebugTunnel_Open(1);
  if (dtData == nullptr) {
    std::fprintf(stderr, "[ERROR] DebugTunnel open failed\n");
    rc = 1;
    goto cleanup;
  }

  // Launch kernel: print + passthrough copy (input -> output via UB).
  LaunchPrint_bridge_kernel_mix_aiv(dtData, v1Device, v2Device, offsetHost,
                                    nHost, stream);

  ACL_CHECK(aclrtSynchronizeStream(stream));
  __DebugTunnel_Close(dtData, stream);
  ACL_CHECK(aclrtMemcpy(v2Host, kFileSize, v2Device, kFileSize,
                        ACL_MEMCPY_DEVICE_TO_HOST));
  if (!WriteFile("./v2.bin", v2Host, kFileSize)) {
    std::fprintf(stderr, "[ERROR] Failed to write ./v2.bin\n");
    rc = 1;
    goto cleanup;
  }

cleanup:
  if (v1Device != nullptr) {
    aclrtFree(v1Device);
  }
  if (v2Device != nullptr) {
    aclrtFree(v2Device);
  }
  if (v1Host != nullptr) {
    aclrtFreeHost(v1Host);
  }
  if (v2Host != nullptr) {
    aclrtFreeHost(v2Host);
  }
  if (stream != nullptr) {
    aclrtDestroyStream(stream);
  }
  if (deviceSet) {
    aclrtResetDevice(deviceId);
  }
  if (aclInited) {
    aclFinalize();
  }
  return rc;
}
